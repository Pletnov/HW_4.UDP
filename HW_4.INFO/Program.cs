Моніторинг інженерних датчиків будівлі

У технічному приміщенні будівлі встановлено кілька датчиків. 
Кожен датчик 10 разів на секунду надсилає по UDP свої показання на сервер моніторингу 
(127.0.0.1, порт 19000). Сервер показує поточний стан усіх активних датчиків.

Проєкт «Датчик»

Під час запуску генерує свій ідентифікатор: випадкове число uint32. 
Ідентифікатор виводиться в консоль.
Кожні 100 мс надсилає пакет з поточними показаннями.
Показання змінюються плавно, на невелику випадкову величину від попереднього значення, 
і не виходять за межі діапазону:
температура: 18–26 °C;
вологість: 30–70 %;
тиск води: 2,0–4,5 бар;
напруга в мережі: 207–253 В.
Можна запустити кілька екземплярів одночасно.

Формат пакета (14 байтів):

Зміщення	Розмір	Поле	Тип і одиниці
0	4	ідентифікатор датчика	uint32
4	2	номер пакета	uint16, зростає з кожним пакетом
6	2	температура	int16, сотні °C (21,57 → 2157)
8	2	вологість	uint16, сотні %
10	2	тиск води	uint16, тисячні бар
12	2	напруга	uint16, десяті В

Проєкт «Сервер моніторингу»

Приймає пакети від будь-якої кількості датчиків. Пакет неправильної довжини не валить сервер, а рахується як «некоректний».
Для кожного датчика зберігає останні показання і час отримання останнього пакета.
Пакет з номером, меншим або рівним останньому прийнятому від цього датчика, ігнорується як запізнілий. Перехід номера через 65 535 до 0 запізненням не вважається.
Раз на 250 мс перемальовує таблицю в консолі 
(Console.SetCursorPosition, без мерехтіння від Console.Clear на кожен пакет). 
Кожен датчик займає окремий рядок: 
ідентифікатор, температура, вологість, тиск, напруга, скільки мілісекунд тому прийшов останній пакет.
Якщо від датчика немає пакетів понад 5 секунд, він зникає з таблиці.
Під таблицею виводиться загальна кількість прийнятих, запізнілих і некоректних пакетів.
Прийом пакетів і перемальовування таблиці працюють у різних задачах. Доступ до спільного словника датчиків потокобезпечний.

Перевірка

Запустити сервер і три датчики. У таблиці три рядки, значення змінюються плавно.
Закрити один датчик. Його рядок зникає приблизно через 5 с, інші рядки працюють без перебоїв.
Запустити новий датчик. З'являється новий рядок з новим ідентифікатором.
Запустити датчик раніше за сервер. Датчик працює без помилок, а сервер підхоплює його одразу після старту.

